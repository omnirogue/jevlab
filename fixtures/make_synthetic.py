"""Regenerate synthetic_sample.json deterministically.

Every item is invented from the templates below: no person, company, ticket or message is real.
The three recorded judges are simulated with fixed noise so the sample shows a calibrated judge,
an overconfident judge and a noisy judge. Run: ``python3 fixtures/make_synthetic.py``.
"""

from __future__ import annotations

import json
import random
from pathlib import Path

GOOD = [
    "Thanks for flagging this. I have issued the refund of {amt} to the original card; it should "
    "appear within {days} business days. Reply here if it has not arrived by then.",
    "You were charged twice for order {order}. I reversed the duplicate charge of {amt} today and "
    "confirmed the order itself is unchanged.",
    "Your plan now renews on the {day}th instead of the 1st, as you asked. The next invoice will "
    "be {amt} and nothing else on the account changed.",
    "I paused the subscription for one month as requested. No charge will be taken until it "
    "resumes, and you can restart it earlier from the account page.",
]
BAD = [
    "We value your feedback and are always working to improve our services.",
    "Please see our help centre for more information about billing questions.",
    "I have escalated this to the relevant team, who will be in touch in due course.",
    "Refunds are subject to our policy. Let us know if there is anything else we can help with.",
]
QUESTIONS = [
    {"id": "resolves", "text": "Does the reply resolve the customer's stated problem?"},
    {"id": "specific", "text": "Does the reply state a concrete amount, date or next step?"},
]


def _clip(p: float) -> float:
    return round(min(max(p, 0.01), 0.99), 3)


def build(seed: int = 20261014, n: int = 40) -> dict:
    rng = random.Random(seed)
    items = []
    for k in range(n):
        truth = rng.random() < 0.5
        template = rng.choice(GOOD if truth else BAD)
        text = template.format(
            amt=f"${rng.randint(9, 199)}.{rng.randint(0, 99):02d}",
            days=rng.randint(3, 10),
            order=f"SAMPLE-{rng.randint(1000, 9999)}",
            day=rng.randint(2, 28),
        )
        base = 0.8 if truth else 0.2
        items.append(
            {
                "id": f"syn-{k + 1:03d}",
                "split": "fit" if k % 2 == 0 else "holdout",
                "question_id": QUESTIONS[(k // 2) % len(QUESTIONS)]["id"],
                "text": text,
                "truth": truth,
                "judgments": {
                    "judge-calibrated": _clip(base + rng.gauss(0, 0.12)),
                    "judge-overconfident": _clip((0.97 if truth else 0.03) + rng.gauss(0, 0.02))
                    if rng.random() > 0.15
                    else _clip(0.97 if not truth else 0.03),
                    "judge-noisy": _clip(0.5 + (0.15 if truth else -0.15) + rng.gauss(0, 0.25)),
                },
            }
        )
    return {
        "schema_version": 1,
        "synthetic": True,
        "license": "Apache-2.0",
        "description": "Fictional billing-support replies generated by fixtures/make_synthetic.py "
        f"(seed {seed}). Judgments are simulated, not model output.",
        "rubric": {"id": "public-reply-quality-v1", "questions": QUESTIONS},
        "items": items,
    }


if __name__ == "__main__":
    out = Path(__file__).with_name("synthetic_sample.json")
    out.write_text(json.dumps(build(), indent=2) + "\n", encoding="utf-8")
    print(f"wrote {out}")
